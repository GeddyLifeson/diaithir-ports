#!/usr/bin/env python3
"""Refine the generic fallback rows of ANIMATIONS_COVERAGE.csv from the per-thing bone lists in compute/jobs/anim_rows-*/out.jsonl.
Usage: python3 -I gen_bone_rules.py <coverage.csv> <jobs-dir> <rules_bones.tsv>
A thing whose bones name a rotor, piston, lid, drawer or crystal gets that motion as an exact-id rule (loaded before rules.tsv).
Run gen_coverage.py afterwards so the CSV picks the rules up."""
import csv, glob, json, sys

cov, jobs, out = sys.argv[1:4]
OWNER = '4-machines-blocks-vehicles'
# first bone group that matches wins: (words in bone name, kind, axis, speed, amount, idle, done, easing)
GROUPS = [
    (('piston', 'plunger', 'ram', 'stamper', 'hammer'), 'PISTON', 'y', 1.2, 0.2, 0, 0, 'LINEAR'),
    (('rotor', 'blade', 'propeller', 'fan', 'gear', 'cog', 'turbine', 'drill', 'wheel', 'flywheel', 'rune_ring', 'orbit_ring', 'spinner'), 'SPIN', 'y', 360, 0, 0, 0, 'LINEAR'),
    (('lid', 'hatch', 'flap', 'door', 'cover'), 'SWING', 'x', 4, -70, 0, 1, 'OUT_BACK'),
    (('drawer',), 'SLIDE', 'z', 3, 0.6, 0, 1, 'IN_OUT'),
    (('crystal', 'orb', 'glow_core'), 'HOVER', 'y', 0.3, 0.04, 1, 1, 'LINEAR'),
]
fallback = {r['thing'] for r in csv.DictReader(open(cov, newline='', encoding='utf-8'))
            if r['owner'] == OWNER and 'generic' in r['engine_route']}
lines = []
seen = set()
for f in sorted(glob.glob(f'{jobs}/anim_rows-*/out.jsonl')):
    for l in open(f, encoding='utf-8'):
        try:
            j = json.loads(json.loads(l)['text'])
        except (ValueError, KeyError):
            continue
        t = j.get('thing')
        if t not in fallback or t in seen:
            continue
        names = [b.lower() for b in j.get('bones', [])]
        for words, kind, ax, sp, am, idle, done, ease in GROUPS:
            if any(w in n for n in names for w in words):
                lines.append('\t'.join(map(str, (t, kind, ax, sp, am, idle, done, ease, 'bones'))))
                seen.add(t)
                break
open(out, 'w', encoding='utf-8').write('# exact-id rules from per-thing bone lists; generated by tools/gen_bone_rules.py, loaded before rules.tsv\n' + '\n'.join(sorted(lines)) + '\n')
print(len(lines), 'of', len(fallback), 'fallback rows refined')
