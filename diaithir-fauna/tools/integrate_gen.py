#!/usr/bin/env python3
"""Integration data for the other Diaithir systems, generated from species.json + the catalogue.

    python3 tools/integrate_gen.py            # writes ../kubejs and src/main/resources/data/diaithir_ages/codex/records
    python3 tools/integrate_gen.py --check    # fails if the files on disk differ

Formats are the ones read in DiaithirRPG PRs #160 (economy), #163 (spoilage), #167 (cuisine), #164 (climate, clothing) and #82 (codex).
See kubejs/NOTES.md for what each file feeds and what is still missing on the other side.
"""
import json, math, re, statistics, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catalogue

ROOT = Path(__file__).resolve().parents[1]
SPECIES = ROOT / "src/main/resources/data/diaithirfauna/species.json"
KJS = ROOT / "kubejs"
CODEX = ROOT / "src/main/resources/data/diaithir_ages/codex/records"
OUT = {}  # path -> text


def put(path, text):
    OUT[Path(path)] = text


def jdump(o, indent=None):
    return json.dumps(o, indent=indent, separators=(",", ":") if indent is None else None, ensure_ascii=False, sort_keys=True) + "\n"


# ---------------------------------------------------------------- load
data = json.loads(SPECIES.read_text(encoding="utf-8"))
cat = {r["id"]: r for r in catalogue.rows("mob") + catalogue.rows("fossil")}
SP = []
for s in data["species"]:
    r = cat[s["id"]]
    notes = {x.strip() for x in r["notes"].split(",")}
    SP.append(dict(s, latin=r["latin"], common=r["common"], notes=notes, habitat=set(r["habitat"].split(";")) if "habitat" in r else set(),
                   range=r.get("range") or r.get("region", ""), period=r.get("period", ""), formation=r.get("formation", ""),
                   ext=r.get("ext", "-")))
PLANS = sorted({s["plan"] for s in SP})

# ---------------------------------------------------------------- (1) economy
# Prices are tw (a twist of salt at par; the market turns tw into each culture's own money by that money's rate, so a fossil costs the
# same labour everywhere and nothing is minted). Older, rarer (higher DNA tier) and bigger animals cost more.
def frag_price(s):
    ma = (s["ma"][0] + s["ma"][1]) / 2
    dna = max(1, s.get("dna", 1))
    return max(6, round(5 * (1 + ma / 25) ** 0.6 * 1.7 ** (dna - 1) * (1 + math.log10(s["kg"] + 1) / 4)))


fossils = {}
for s in SP:
    if not s.get("fossil"):
        continue
    f = frag_price(s)
    fossils[s["id"]] = dict(fragment=f, cleaned=4 * f, ma=s["ma"], dna=s.get("dna", 1), period=s["period"], rock=s["rock"])
med = int(statistics.median(v["fragment"] for v in fossils.values()))
PRICES = {"diaithirfauna:fossil_fragment": [med, round(20 + 20 * math.log10(med))],
          "diaithirfauna:cleaned_fossil": [4 * med, round(20 + 20 * math.log10(4 * med))],
          "diaithirfauna:preparation_bench": [40, 52]}
for rock in data["rocks"]:
    PRICES[f"diaithirfauna:fossil_{rock}"] = [8, 28]
put(KJS / "data/diaithir/prices_fauna.json", jdump(PRICES))
put(KJS / "data/diaithirfauna/fossil_values.json", jdump(dict(
    _doc="tw per item by species (custom_data Species on fossil_fragment / cleaned_fossil). Item price in prices_fauna.json is the median; "
         "the market sells by item id only, so global.FAUNA_FOSSIL_TW(stack) answers this table for a market hook.",
    median=med, species=fossils)))
stock = lambda p: max(4, min(64, round(32 / max(p, 0.5))))  # vendors.py: WAGE_TW 32
ITEMS = ["diaithirfauna:fossil_fragment", "diaithirfauna:cleaned_fossil", "diaithirfauna:preparation_bench"] + [f"diaithirfauna:fossil_{r}" for r in data["rocks"]]
put(KJS / "data/diaithir/vendors_fauna.json", jdump(dict(
    _doc="Age III antiquarians, generated by diaithir-fauna/tools/integrate_gen.py in the shape of vendors_age3.json; zz_fauna.js merges it.",
    age="III", vendors=[dict(id="antiquarian", name="Antiquarian", role="Antiquarian", spawn=["every settlement", "library"], needs="writing",
                             items={i: dict(price=PRICES[i][0], stock=stock(PRICES[i][0])) for i in ITEMS})]), indent=1))

# ---------------------------------------------------------------- (3)(4) cuisine meat categories, hides and fur
WATERFISH = re.compile(r"^(fish_|eel$|ray$|syngnathid$|placoderm$)")
SHELL = {"crab", "cephalopod", "starfish", "jellyfish", "ammonite", "giant_arthropod", "eurypterid", "trilobite", "scorpion", "beetle", "insect_flying"}
BIRDS = {"songbird", "raptor", "wader", "waterfowl", "galliform", "seabird", "parrot", "penguin", "ratite", "corvid", "owl", "pigeon", "terror_bird"}
PORK = re.compile(r"boar|pig$|hog|peccary|babirusa|warthog")
LAMB = re.compile(r"sheep|mouflon|argali|bighorn")
GOAT = re.compile(r"goat|ibex|chamois|tahr|markhor")
BEEF = re.compile(r"cattle|aurochs|bison|buffalo|yak|gaur|banteng|zebu|ox$")
COLD = {"taiga", "icy", "tundra", "mountain", "ocean_cold"}


def meat(s):
    p = s["plan"].split(":")[-1]
    edible = bool({"edible", "huntable"} & s["notes"])
    kg, i = s["kg"], s["id"]
    if WATERFISH.match(p):
        return ("fish", None)
    if p in SHELL:
        return ("exotic", "exotic" if edible else None)
    if p in BIRDS:
        fam = {"waterfowl": "goose" if kg >= 3 else "duck", "pigeon": "pigeon",
               "galliform": "quail" if kg < 0.4 else "turkey" if kg >= 5 else "chicken"}.get(p, "chicken" if edible else None)
        return ("poultry", fam)
    if p == "lagomorph":
        return ("game", "rabbit")
    if PORK.search(i):
        return ("game", "pork")
    if LAMB.search(i):
        return ("game", "lamb")
    if GOAT.search(i):
        return ("game", "goat")
    if BEEF.search(i):
        return ("game", "beef")
    if p in {"lizard", "crocodilian", "frog", "sea_turtle", "pinniped", "dolphin", "archaic_whale", "insectivore", "bat", "monotreme", "armadillo"}:
        return ("exotic", "exotic" if edible else None)
    if s["diet"] in {"herb", "frug"} or "huntable" in s["notes"]:
        return ("game", "game")
    return ("exotic", "exotic" if edible else None)


def hide(s):
    """(kind, count, warm). fur = minecraft:rabbit_hide (the clothing module's fur), leather = raw_hide (rots until tanned)."""
    p, kg, n = s["plan"].split(":")[-1], s["kg"], s["notes"]
    if WATERFISH.match(p) or p in BIRDS or p in SHELL or p in {"starfish"}:
        return ("none", 0, False)
    cold = bool(COLD & s["habitat"]) or "hibernates" in n
    base = max(1, min(8, int(math.sqrt(kg) / 5)))
    if "fur" in n and kg >= 1:
        warm = cold and kg >= 20
        return ("fur", base * (2 if warm else 1) if kg >= 20 else 1, warm)
    if kg >= 20 and not ({"feather", "shell"} & n):
        return ("leather", base, False)
    return ("none", 0, False)


DROPS = {}
for s in SP:
    if s.get("fossil"):
        continue
    c, fam = meat(s)
    h, hn, warm = hide(s)
    DROPS[s["id"]] = dict(cat=c, fam=fam, chance=round(min(0.6, 0.2 + 0.1 * math.log10(s["kg"] + 1)), 2), hide=h, hn=hn, warm=warm)
put(KJS / "data/diaithirfauna/fauna_drops.json", jdump(dict(
    _doc="Per living species: cat (fish, poultry, game, exotic) is the meat category dishes use; fam is the cuisine cut family (global.CUISINE.cuts) or null; "
         "hide fur = minecraft:rabbit_hide (fur of the clothing recipes), leather = diaithir:raw_hide (spoilage tans it), none = no hide; warm = cold-climate "
         "large furred mammal (double fur).", species=DROPS)))
put(KJS / "server_scripts/diaithirfauna/fauna_drops.js", f"""// Written by diaithir-fauna/tools/integrate_gen.py. Fauna drops joined to cuisine (#167 cuts), spoilage (#163 raw_hide) and clothing (#164 fur).
// The mod itself drops vanilla meat, leather, feather and bone; this swaps the hide by species and adds the cuisine cut of the animal's family.
const FAUNA_PLANS = {json.dumps(PLANS)}
let FAUNA_DROPS = {{}}
ServerEvents.loaded(() => {{
  try {{ FAUNA_DROPS = (JsonIO.read('kubejs/data/diaithirfauna/fauna_drops.json') || {{ species: {{}} }}).species }} catch (e) {{ console.warn('[fauna] no drop table: ' + e) }}
}})
const faunaSpeciesOf = e => {{
  try {{ let n = e.nbt; let v = n.getStringOr ? n.getStringOr('Species', '') : n.getString('Species'); return String(v) }} catch (x) {{ return '' }}
}}
FAUNA_PLANS.forEach(plan => EntityEvents.drops('diaithirfauna:' + plan, event => {{
  let d = FAUNA_DROPS[faunaSpeciesOf(event.entity)]
  if (!d) return
  // hide: the mod drops leather for land animals of 20 kg and up
  if (d.hide === 'none') event.drops.removeIf(i => String(i.item.id) === 'minecraft:leather')
  else event.drops.forEach(i => {{
    if (String(i.item.id) !== 'minecraft:leather') return
    i.setItem(Item.of(d.hide === 'fur' ? 'minecraft:rabbit_hide' : 'diaithir:raw_hide', d.hn))
  }})
  if (d.hide === 'fur' && d.hn > 0 && !event.drops.stream().anyMatch(i => String(i.item.id) === 'minecraft:rabbit_hide')) event.addDrop(Item.of('minecraft:rabbit_hide', d.hn))
  // cuisine cut of the family (global.CUISINE.cuts is [family, main cut id]); skipped when the butchery mod gives carcasses
  if (d.fam && global.CUISINE && !Platform.isLoaded('diaithirbutchery') && Math.random() < d.chance)
    for (let c of global.CUISINE.cuts) if (c[0] === d.fam) {{ event.addDrop(Item.of(c[1])); break }}
}}))
""")

# ---------------------------------------------------------------- economy hook script
put(KJS / "server_scripts/economy/zz_fauna.js", """// Written by diaithir-fauna/tools/integrate_gen.py. Runs after market.js (zz): adds the fossil goods and the antiquarian to the economy tables.
// Fossils are Age III goods (Cenozoic digs); the antiquarian takes the cartographer's place in Age III (ANTIQUARIAN_PROFESSION), Age IV's scribe replaces it as before.
const ANTIQUARIAN_PROFESSION = 'cartographer'
;(function () {
  if (typeof ECON_GOODS === 'undefined' || typeof ECON_VENDOR_DATA === 'undefined') return
  let prices = JsonIO.read('kubejs/data/diaithir/prices_fauna.json') || {}
  for (let id in prices) {
    ECON_PRICES[id] = prices[id]
    ECON_GOODS[id] = [prices[id][0], Math.max(8, Math.round(256 / Math.sqrt(prices[id][0]))), 'III']
  }
  let v = JsonIO.read('kubejs/data/diaithir/vendors_fauna.json')
  if (v && v.vendors) v.vendors.forEach(x => { if (!(ECON_VENDOR_DATA.III || []).some(y => y.id === x.id)) (ECON_VENDOR_DATA.III = ECON_VENDOR_DATA.III || []).push(x) })
  if (typeof ECON_PROF_VENDOR !== 'undefined' && ECON_PROF_VENDOR[2]) ECON_PROF_VENDOR[2][ANTIQUARIAN_PROFESSION] = 'antiquarian'
  // per-species worth of a fossil stack, for a market hook: tw for one item, or null
  let values = (JsonIO.read('kubejs/data/diaithirfauna/fossil_values.json') || { species: {} }).species
  global.FAUNA_FOSSIL_TW = stack => {
    try {
      let sp = String(stack.nbt.getCompound('components').getCompound('minecraft:custom_data').getStringOr('Species', ''))
      let r = values[sp]
      return r ? (String(stack.id).endsWith('cleaned_fossil') ? r.cleaned : r.fragment) : null
    } catch (e) { return null }
  }
})()
""")

# ---------------------------------------------------------------- (2) spoilage check
covered = {"minecraft:beef": "meat 20%", "minecraft:porkchop": "meat 20%", "minecraft:cod": "meat 20%", "minecraft:chicken": "meat 20%",
           "diaithir:raw_hide": "hide 25%", "minecraft:rabbit_hide": "never", "minecraft:leather": "never", "minecraft:feather": "not food", "minecraft:bone": "not food",
           "diaithirfauna:fossil_fragment": "not food, never", "diaithirfauna:cleaned_fossil": "not food, never"}
for rock in data["rocks"]:
    covered[f"diaithirfauna:fossil_{rock}"] = "block, never"
put(KJS / "data/diaithirfauna/spoilage_coverage.json", jdump(dict(
    _doc="Every item the fauna mod drops, and the spoilage rule (content/spoilage rates.js) that covers it. Meat and hides are vanilla ids the module already names; "
         "fossils are not food, so Spoiled never gives them a timer (spoilEverything=false).", items=covered)))

# ---------------------------------------------------------------- (5) codex records (shelfmark, name, kind, age, text, ids; optional so the completion quest is unaffected)
def rec(shelf, name, kind, age, text, ids, stats=None):
    r = dict(shelfmark=shelf, name=name, kind=kind, age=age, band="", moth="", text=text, ids=ids, optional=True)
    if stats:
        r["stats"] = stats
    return r


def kg_txt(kg):
    return f"{kg:g} kg" if kg < 1000 else f"{kg / 1000:g} t"


DIET = dict(carn="meat-eater", herb="plant-eater", omni="eats both", insect="insect-eater", pisc="fish-eater", frug="fruit-eater", fil="filter-feeder", nect="nectar-feeder", scav="scavenger")
living, fos = [], {"III": [], "IV": [], "V": []}
for s in SP:
    diet = DIET.get(s["diet"], s["diet"])
    if s.get("fossil"):
        age = {"Cenozoic": "III", "Mesozoic": "IV", "Paleozoic": "V"}[
            "Cenozoic" if s["ma"][0] <= 66 else "Mesozoic" if s["ma"][0] <= 252 else "Paleozoic"]
        fos[age].append(rec(f"Σ › P › {s['id']}", s["common"], "being", age,
                            f"A {diet} of the {s['period']}, found in the {s['formation']} ({s['range']}), {kg_txt(s['kg'])} grown. Its bones lie in {s['rock'].replace('_', ' ')}.",
                            [f"fossil:diaithirfauna:{s['id']}"],
                            [f"Age: {s['ma'][0]:g} to {s['ma'][1]:g} million years", f"DNA tier: {s.get('dna', 1)}", f"Mass: {kg_txt(s['kg'])}", f"Value: {fossils[s['id']]['fragment']} tw a fragment"]))
    else:
        gone = s["ext"] not in ("-", "")
        living.append(rec(f"Σ › F › {s['id']}", s["common"], "being", "I",
                          f"A {diet} ({s['latin']}), {kg_txt(s['kg'])} grown, of {s['range'].replace(';', ', ')}." + (f" Gone from the world by the year {s['ext']}." if gone else ""),
                          [f"species:diaithirfauna:{s['id']}"],
                          [f"Diet: {diet}", f"Mass: {kg_txt(s['kg'])}", f"Meat: {DROPS[s['id']]['cat']}"]))
plan_recs = [rec(f"Σ › F › body_{p}", p.replace("_", " ").capitalize() + " (field note)", "being", "I",
                 "A body of this shape; scan an individual for its kind.", [f"entity:diaithirfauna:{p}"]) for p in PLANS]
item_recs = [rec("Σ › P › fossil_fragment", "Fossil fragment", "thing", "III", "A shard of old bone from the strata. A brush and a preparation bench show what it was.", ["item:diaithirfauna:fossil_fragment"]),
             rec("Σ › P › cleaned_fossil", "Cleaned fossil", "thing", "III", "Bone cleaned of its rock, ready to be studied or sold to an antiquarian.", ["item:diaithirfauna:cleaned_fossil"]),
             rec("Σ › P › preparation_bench", "Preparation bench", "thing", "III", "A bench and a brush for freeing fossils from the stone.", ["item:diaithirfauna:preparation_bench"])] + [
    rec(f"Σ › P › fossil_{r}", f"Fossil {r.replace('_', ' ')}", "thing", "III", "Rock that holds old bones. Dig it and see what the strata give.", [f"item:diaithirfauna:fossil_{r}"]) for r in data["rocks"]]
put(CODEX / "I/fauna.json", jdump(living + plan_recs))
for a, l in fos.items():
    put(CODEX / f"{a}/fossils.json", jdump(l + (item_recs if a == "III" else [])))

# ---------------------------------------------------------------- write
if __name__ == "__main__":
    bad = []
    for p, t in OUT.items():
        if "--check" in sys.argv:
            if not p.exists() or p.read_text(encoding="utf-8") != t:
                bad.append(str(p))
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(t, encoding="utf-8")
    print(len(OUT), "files;", len(DROPS), "living species,", len(fossils), "fossil taxa, median fragment", med, "tw;", "stale: " + ", ".join(bad) if bad else "ok")
    sys.exit(1 if bad else 0)
