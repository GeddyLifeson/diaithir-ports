#!/usr/bin/env python3
"""Builds data/diaithirgear/bullet_parity.json and the diaithir:ammo/<calibre> item tags.

Usage: gen_parity.py <path to Point Blank jar>   (the jar is only read for numeric facts: gun id, calibre, rpm, per-hit damage;
nothing of it is copied). Energies are public muzzle-energy figures in joules.

Parity rule: a hit of calibre C should do  musket * sqrt(E_C / E_musket)  damage, scaled down for fast fire by
R = clamp(sqrt(ref_rpm / rpm), floor, 1), so Age VII rounds beat the Age IV musket ball per hit without
turning automatic fire into a damage-per-second jump. multiplier = parity_hit / base_hit, applied at runtime.
"""
import json, math, sys, zipfile, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "src/main/resources/data"
MUSKET_DAMAGE, MUSKET_ENERGY = 16.0, 1800.0     # musketmod default Config.MUSKET_DAMAGE, round ball ~ 1800 J
REF_RPM, FLOOR = 120.0, 0.6
# calibre tag -> (point blank ammo item, muzzle energy J, Age)
CAL = {
    "9x19":    ("ammo9mm", 500, "VII"), "45acp": ("ammo45acp", 480, "V"), "357mag": ("ammo357", 750, "V"),
    "50ae":    ("ammo50ae", 1600, "VII"), "46x30": ("ammo46", 450, "VII"), "57x28": ("ammo57", 400, "VII"),
    "545x39":  ("ammo545", 1400, "VII"), "556x45": ("ammo556", 1750, "VII"), "762x39": ("ammo762", 2000, "VII"),
    "762x51":  ("ammo762x51", 3400, "VII"), "68x51": ("ammo68", 4000, "VII"), "338lapua": ("ammo338lapua", 6500, "VII"),
    "50bmg":   ("ammo50bmg", 17000, "VII"), "12ga": ("ammo12gauge", 2500, "VII"),
}
BY_AMMO = {v[0]: k for k, v in CAL.items()}

def modes(d):
    out = []
    for f in d.get("features", []):
        if f.get("type") == "FIREMODE":
            out += f.get("fireModes", [])
    return out

def main(jar):
    z = zipfile.ZipFile(jar)
    guns = {}
    for n in sorted(z.namelist()):
        if not (n.startswith("data/pointblank/items/") and n.endswith(".json")):
            continue
        d = json.loads(z.read(n))
        if str(d.get("type")).lower() != "gun":
            continue
        cal = next((BY_AMMO[a] for a in d.get("compatibleAmmo", []) if a in BY_AMMO), None)
        if cal is None:
            continue  # rockets, lasers, grenade launchers: explosion damage, not touched
        ms = [m for m in modes(d) if "ammo" not in m and m.get("damage") is not None]
        m0 = ms[0] if ms else {}
        base = m0.get("damage", d.get("damage")); rpm = m0.get("rpm", d.get("rpm")); pel = m0.get("pelletCount") or d.get("pelletCount") or d.get("pellets") or 1
        if not base or not rpm:
            continue
        guns[d["name"]] = dict(calibre=cal, base=base, rpm=rpm, pellets=pel)
    for g in guns.values():
        e = CAL[g["calibre"]][1]
        hit_total = MUSKET_DAMAGE * math.sqrt(e / MUSKET_ENERGY)
        r = min(1.0, max(FLOOR, math.sqrt(REF_RPM / g["rpm"])))
        g["parity_hit"] = round(hit_total * r / g["pellets"], 3)
        g["mult"] = round(g["parity_hit"] / g["base"], 3)
    out = dict(
        _doc="Per-hit damage parity of Point Blank guns against the Musket Mod (musketmod:cartridge, Age IV, 16 per ball). Generated by tools/gen_parity.py; mult is applied to every bullet hit of that gun (pellets individually). Override: config/diaithirgear/bullet_parity.json.",
        musket=dict(item="musketmod:cartridge", damage=MUSKET_DAMAGE, energy_j=MUSKET_ENERGY, age="IV"),
        calibres={k: dict(ammo="pointblank:" + v[0], energy_j=v[1], age=v[2]) for k, v in CAL.items()},
        guns={"pointblank:" + k: v for k, v in sorted(guns.items())})
    (RES / "diaithirgear").mkdir(parents=True, exist_ok=True)
    (RES / "diaithirgear/bullet_parity.json").write_text(json.dumps(out, indent=1))
    tdir = RES / "diaithir/tags/item/ammo"; tdir.mkdir(parents=True, exist_ok=True)
    for k, v in CAL.items():
        (tdir / f"{k}.json").write_text(json.dumps({"replace": False, "values": [{"id": "pointblank:" + v[0], "required": False}]}, indent=1))
    (tdir / "cartridge.json").write_text(json.dumps({"replace": False, "values": [{"id": "musketmod:cartridge", "required": False}]}, indent=1))
    (tdir / "bullets.json").write_text(json.dumps({"replace": False, "values": [{"id": "#diaithir:ammo/cartridge", "required": False}] + [{"id": "#diaithir:ammo/" + k, "required": False} for k in CAL]}, indent=1))
    age = {"musketmod": "IV", "pointblank": "VI", "diaithirgear": "IV"}
    items = {"musketmod:cartridge": "IV"}
    items.update({"pointblank:" + v[0]: v[2] for v in CAL.values()})
    (ROOT / "age_gates.json").write_text(json.dumps({"_doc": "Same shape as DiaithirRPG content/tech_ages.json. Items beat namespaces. Calibres follow the decided pointblank ages (.45 and .357 Age V), the rest Age VII; the musket cartridge is the Age IV baseline. Set families gate in data/diaithirgear/set_bonuses.", "namespaces": {"diaithirgear": "IV"}, "items": items}, indent=1))
    print(len(guns), "guns")
    for k, g in sorted(guns.items()):
        print(k, g["calibre"], g["base"], g["rpm"], "->", g["parity_hit"], "x", g["mult"])

main(sys.argv[1])
