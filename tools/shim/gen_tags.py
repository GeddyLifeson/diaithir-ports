#!/usr/bin/env python3
"""Generate com.simibubi.create.AllTags (enum-style tag holders) over the port's AllBlockTags/AllItemTags/AllFluidTags.
Usage: gen_tags.py port.jar out.java"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import cf
port, out = sys.argv[1:3]
want = {'AllBlockTags': ('Block', 'net.minecraft.world.level.block.Block'), 'AllItemTags': ('Item', 'net.minecraft.world.item.Item'),
        'AllFluidTags': ('Fluid', 'net.minecraft.world.level.material.Fluid')}
names = {}
for _, c in cf.jar_classes(port):
    k = c['name'].split('/')[-1]
    if c['name'] == 'com/zurrtum/create/' + k and k in want:
        names[k] = [n for n, d, a in c['fields'] if a & 8 and d == 'Lnet/minecraft/tags/TagKey;']
S = ['package com.simibubi.create;\n\nimport net.minecraft.core.registries.Registries;\nimport net.minecraft.resources.Identifier;\nimport net.minecraft.tags.TagKey;\n'
     'import net.minecraft.world.item.ItemStack;\nimport net.minecraft.world.level.block.state.BlockState;\n\n/** GENERATED by tools/shim/gen_tags.py over the port tag classes. */\npublic class AllTags {\n'
     '    public static TagKey<net.minecraft.world.item.Item> commonItemTag(String path) { return TagKey.create(Registries.ITEM, Identifier.fromNamespaceAndPath("c", path)); }\n'
     '    public static TagKey<net.minecraft.world.level.block.Block> commonBlockTag(String path) { return TagKey.create(Registries.BLOCK, Identifier.fromNamespaceAndPath("c", path)); }\n'
     '    public static TagKey<net.minecraft.world.level.material.Fluid> commonFluidTag(String path) { return TagKey.create(Registries.FLUID, Identifier.fromNamespaceAndPath("c", path)); }\n']
for cls, (T, fq) in want.items():
    enum = 'AllBlockTags' if cls == 'AllBlockTags' else cls
    S.append('\n    public enum %s {\n        %s;\n        public final TagKey<%s> tag;\n        %s(TagKey<%s> t) { this.tag = t; }\n' % (
        enum, ',\n        '.join('%s(com.zurrtum.create.%s.%s)' % (n, cls, n) for n in names.get(cls, [])), fq, enum, fq))
    if T == 'Block':
        S.append('        public boolean matches(BlockState s) { return s.is(tag); }\n        public boolean matches(ItemStack s) { return s.getItem() instanceof net.minecraft.world.item.BlockItem b && b.getBlock().defaultBlockState().is(tag); }\n')
    elif T == 'Item':
        S.append('        public boolean matches(ItemStack s) { return s.is(tag); }\n')
    S.append('    }\n')
S.append('}\n')
open(out, 'w').write(''.join(S)); print({k: len(v) for k, v in names.items()})
