#!/usr/bin/env python3
"""Generate adapter classes com.simibubi.create.{AllBlocks,AllItems} whose static fields are Registrate entries
wrapping the port's directly-registered Block/Item objects (looked up by reflection, resolved to registry keys).
Usage: gen_entries.py port.jar server.jar out_src_dir"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import cf
port, server, out = sys.argv[1:4]
sup = {}
for j in (port, server):
    for _, c in cf.jar_classes(j): sup[c['name']] = c['super']
def is_a(n, target):
    while n:
        if n == target: return True
        n = sup.get(n)
    return False
fields = {}
for _, c in cf.jar_classes(port):
    if c['name'] in ('com/zurrtum/create/AllBlocks', 'com/zurrtum/create/AllItems'):
        fields[c['name']] = [(n, d) for n, d, a in c['fields'] if a & 0x8 and a & 0x1 and d.startswith('L')]
HEAD = '''package com.simibubi.create;

import com.tterrag.registrate.util.entry.%(E)s;
import com.simibubi.create.foundation.data.CreateRegistrate;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.%(P)s;
import net.neoforged.neoforge.registries.DeferredHolder;

/** GENERATED by tools/shim/gen_entries.py: Registrate-entry view of the port's %(N)s. */
public class %(N)s {
    private static final CreateRegistrate OWNER = CreateRegistrate.create("create");
    @SuppressWarnings({"unchecked", "rawtypes"})
    private static %(E)s e(String f) {
        try {
            Object o = Class.forName("com.zurrtum.create.%(N)s").getField(f).get(null);
            return new %(E)s(OWNER, DeferredHolder.create(Registries.%(R)s, BuiltInRegistries.%(R)s.getKey((%(T)s) o)));
        } catch (ReflectiveOperationException ex) { throw new IllegalStateException(ex); }
    }
'''
for N, E, R, T, P, base in (('AllBlocks', 'BlockEntry', 'BLOCK', 'Block', 'level.block.Block', 'net/minecraft/world/level/block/Block'),
                            ('AllItems', 'ItemEntry', 'ITEM', 'Item', 'item.Item', 'net/minecraft/world/item/Item')):
    L = [HEAD % dict(N=N, E=E, R=R, T=T, P=P)]
    n = 0
    for f, d in fields['com/zurrtum/create/' + N]:
        if is_a(d[1:-1], base):
            L.append('    public static final %s %s = e("%s");\n' % (E, f, f)); n += 1
    L.append('}\n')
    open(os.path.join(out, N + '.java'), 'w').write(''.join(L)); print(N, n, 'fields')
