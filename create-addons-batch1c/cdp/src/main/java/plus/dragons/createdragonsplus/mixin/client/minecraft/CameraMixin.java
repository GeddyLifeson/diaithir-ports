package plus.dragons.createdragonsplus.mixin.client.minecraft;

import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import net.minecraft.client.Camera;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.material.Fluid;
import net.minecraft.world.level.material.FluidState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import plus.dragons.createdragonsplus.registry.CDPTags;

@Mixin(Camera.class)
public abstract class CameraMixin {
    @WrapOperation(method = "getFluidInCamera", at = @At(value = "INVOKE", target = "Lnet/minecraft/world/level/material/FluidState;is(Lnet/minecraft/tags/TagKey;)Z", ordinal = 0))
    private boolean createDragonsPlus$recognizeSwimmableFluid(
            FluidState state, TagKey<Fluid> tag, Operation<Boolean> original) {
        return original.call(state, tag) || state.is(CDPTags.SWIMMABLE_FLUIDS);
    }
}
