# S6860 Write upgrade compat shims: scan a mod's real blockstates for working-block names and emit target rules.
"""usage: python3 -I gen_shims.py <mod-source-dir> <namespace> <out.json> [priority]
Only ids that have a real blockstate file are written; names are matched by keyword, so review the output."""
import json, pathlib, re, sys

PROCESS = r"furnace|smelter|press|crusher|grinder|mill|kiln|oven|brewer|compressor|drill|pump|assembler|centrifuge|extractor|miner|quarry|cooker|stove|fermenter|cauldron|pulverizer|macerator|washer|mixer|sawmill|incubator|smoker|roaster|refinery|reactor|electrolyzer|forge|anvil|altar|enchant|infuser|focus|crucible"
POWER = r"generator|engine|boiler|turbine|dynamo|reactor"

def main():
    src, ns, out = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3]
    prio = int(sys.argv[4]) if len(sys.argv) > 4 else 100
    ids = sorted({p.stem for p in src.glob(f"**/assets/{ns}/blockstates/*.json")})
    rules = []
    for i in ids:
        if re.search(r"pipe|tube|hatch|concrete|windmill|creative_|compressed_(brick|iron|stone)|miners_star|_block$|^dark_altar_", i):
            continue
        if re.search(r"_(slab|stairs|wall|fence|door|plate|lamp|brick|bricks|casing|frame|pillar)$", i):
            continue
        if re.search(POWER, i):
            rules.append((i, ["speed", "efficiency"], 2))
        elif re.search(PROCESS, i):
            rules.append((i, ["speed", "productivity", "efficiency", "quality"], 2))
    doc = {"_comment": "Generated by tools/gen_shims.py from real blockstate names; keyword match, review before relying on it.",
           "rules": [{"pattern": f"{ns}:{i}", "priority": prio, "slots": s, "allowed": a, "max_quality": 2} for i, a, s in rules]}
    pathlib.Path(out).write_text(json.dumps(doc, indent=1))
    print(f"{ns}: {len(rules)} of {len(ids)} blockstates")

main()
