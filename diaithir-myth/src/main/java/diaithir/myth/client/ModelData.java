package diaithir.myth.client;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import diaithir.myth.DiaithirMyth;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/** Box geometry of one creature, read from assets/diaithir_myth/myth_models/ID.json (generated by tools/gen_myth.py). */
public final class ModelData {
    public final int texW, texH;
    public final List<String> names = new ArrayList<>();
    /** part name -> parent chain from the top down, ending with the part itself */
    public final Map<String, List<String>> paths = new HashMap<>();
    private final JsonArray parts;

    public ModelData(String id) {
        try (var in = ModelData.class.getResourceAsStream("/assets/" + DiaithirMyth.MODID + "/myth_models/" + id + ".json")) {
            JsonObject o = new Gson().fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), JsonObject.class);
            texW = o.getAsJsonArray("tex").get(0).getAsInt();
            texH = o.getAsJsonArray("tex").get(1).getAsInt();
            parts = o.getAsJsonArray("parts");
        } catch (Exception e) {
            throw new IllegalStateException("cannot read model " + id, e);
        }
        Map<String, String> parents = new HashMap<>();
        for (var e : parts) {
            JsonObject p = e.getAsJsonObject();
            String n = p.get("name").getAsString();
            names.add(n);
            parents.put(n, p.get("parent").isJsonNull() ? null : p.get("parent").getAsString());
        }
        for (String n : names) {
            List<String> chain = new ArrayList<>();
            for (String c = n; c != null; c = parents.get(c)) {
                chain.add(0, c);
            }
            paths.put(n, chain);
        }
    }

    public LayerDefinition layer() {
        MeshDefinition mesh = new MeshDefinition();
        Map<String, PartDefinition> defs = new HashMap<>();
        for (var e : parts) {
            JsonObject p = e.getAsJsonObject();
            CubeListBuilder cubes = CubeListBuilder.create();
            for (var be : p.getAsJsonArray("boxes")) {
                JsonArray b = be.getAsJsonArray();
                cubes.texOffs(b.get(0).getAsInt(), b.get(1).getAsInt())
                        .addBox(b.get(2).getAsFloat(), b.get(3).getAsFloat(), b.get(4).getAsFloat(),
                                b.get(5).getAsFloat(), b.get(6).getAsFloat(), b.get(7).getAsFloat());
            }
            JsonArray pv = p.getAsJsonArray("pivot"), r = p.getAsJsonArray("rot");
            PartPose pose = PartPose.offsetAndRotation(pv.get(0).getAsFloat(), pv.get(1).getAsFloat(), pv.get(2).getAsFloat(),
                    r.get(0).getAsFloat(), r.get(1).getAsFloat(), r.get(2).getAsFloat());
            PartDefinition parent = p.get("parent").isJsonNull() ? mesh.getRoot() : defs.get(p.get("parent").getAsString());
            defs.put(p.get("name").getAsString(), parent.addOrReplaceChild(p.get("name").getAsString(), cubes, pose));
        }
        return LayerDefinition.create(mesh, texW, texH);
    }
}
